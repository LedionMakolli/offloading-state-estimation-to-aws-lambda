"""Bake one virtual-IMU window into a C header for the device to publish.

E4b measures the round trip, and a round trip does not care what the samples
contain -- only how many bytes they occupy. So rather than run the vIMU on the
Pico (which is a separate piece of work), one window is generated here by the
same vimu-gen pipeline used everywhere else in this project and shipped in
flash. The device varies only seq, t_start_us and t_sent_us per publish.

This keeps the latency measurement honest in both directions: the payload is
exactly the size and shape the real system would send, and it is real vIMU data
rather than zeros, so the Lambda does genuine work on it instead of hitting a
degenerate fast path.

    python tools/gen_window.py [--fs 200] [--window 2.0]

Writes firmware/src/aws_window.h.
"""

from __future__ import annotations

import argparse
import base64
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "vimu-gen"))

import noise_model as nm      # noqa: E402
import trajectory as tj       # noqa: E402

OUT = HERE.parent / "src" / "aws_window.h"


def c_string(name: str, s: str, per_line: int = 96) -> str:
    """Emit a long base64 blob as concatenated string literals.

    A single 3200-character literal is legal but exceeds the 4095-character
    minimum that C99 guarantees an implementation must support, so it is split.
    """
    chunks = [s[i:i + per_line] for i in range(0, len(s), per_line)]
    body = "\n    ".join('"%s"' % c for c in chunks)
    return "#define %s \\\n    %s\n" % (name, body.replace("\n", " \\\n"))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fs", type=float, default=200.0)
    ap.add_argument("--window", type=float, default=2.0)
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()

    n = int(round(args.window * args.fs))
    traj = tj.MissionTrajectory().generate(args.window + 4.0, args.fs)
    rng = np.random.default_rng(args.seed)

    # apply_deterministic=False: scale-factor and misalignment errors belong to
    # the estimator study, not to a payload whose only job is to be the right
    # size and to be well-formed.
    gyro, _ = nm.synthesise_triad(traj.omega_body, nm.gyro_spec(), traj.dt, rng,
                                  nm.GYRO_RANGES, apply_deterministic=False)
    accel, _ = nm.synthesise_triad(traj.accel_body, nm.accel_spec(), traj.dt,
                                   rng, nm.ACCEL_RANGES,
                                   apply_deterministic=False)

    gyro_lsb = 131.0 / nm.DEG            # FS_SEL = 0, +/- 250 deg/s
    accel_lsb = 16384.0 / 9.80665        # AFS_SEL = 0, +/- 2 g

    def enc(sig, lsb):
        counts = np.clip(np.round(sig[:n] * lsb), -32768, 32767).astype("<i2")
        return base64.b64encode(counts.tobytes()).decode("ascii")

    g_b64, a_b64 = enc(gyro, gyro_lsb), enc(accel, accel_lsb)
    q0, v0, p0 = traj.quat[0], traj.velocity[0], traj.position[0]

    head = """/* Generated by tools/gen_window.py -- do not edit.
 *
 * One virtual-IMU window, produced by the vimu-gen pipeline and frozen into
 * flash so that E4b measures network and cloud latency rather than on-device
 * sample generation. %d samples at %.1f Hz over %.1f s.
 *
 * Encoding matches what the Lambda expects: little-endian int16 counts at the
 * MPU-6050's FS_SEL=0 / AFS_SEL=0 sensitivities, base64 of the raw bytes.
 */
#ifndef AWS_WINDOW_H
#define AWS_WINDOW_H

#define AWS_WINDOW_N        %d
#define AWS_WINDOW_FS       %.1f
#define AWS_WINDOW_DT_US    %d

/* Initial navigation state for the window, scalar-first quaternion. */
#define AWS_WINDOW_Q0       "%.9f,%.9f,%.9f,%.9f"
#define AWS_WINDOW_V0       "%.6f,%.6f,%.6f"
#define AWS_WINDOW_P0       "%.6f,%.6f,%.6f"

""" % (n, args.fs, args.window, n, args.fs,
       int(round(1e6 / args.fs)),
       q0[0], q0[1], q0[2], q0[3],
       v0[0], v0[1], v0[2],
       p0[0], p0[1], p0[2])

    tail = """
#define AWS_WINDOW_GYRO_LEN   %d
#define AWS_WINDOW_ACCEL_LEN  %d

#endif /* AWS_WINDOW_H */
""" % (len(g_b64), len(a_b64))

    OUT.write_text(head + c_string("AWS_WINDOW_GYRO_B64", g_b64) + "\n"
                   + c_string("AWS_WINDOW_ACCEL_B64", a_b64) + tail,
                   encoding="utf-8")

    print("wrote %s" % OUT)
    print("  samples      : %d at %.1f Hz (%.1f s)" % (n, args.fs, args.window))
    print("  gyro base64  : %d chars" % len(g_b64))
    print("  accel base64 : %d chars" % len(a_b64))
    print("  JSON payload : about %.1f kB" % ((len(g_b64) + len(a_b64) + 320) / 1024))
    return 0


if __name__ == "__main__":
    sys.exit(main())
